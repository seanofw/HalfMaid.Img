namespace HalfMaid.Img.Fonts
{
	/// <summary>
	/// Font styles:  Normal, italic, or oblique.
	/// </summary>
	public enum FontStyle : byte
	{
		/// <summary>
		/// Normal font style.
		/// </summary>
		Normal = 0,

		/// <summary>
		/// Italic font style (not to be confused with oblique).
		/// </summary>
		Italic,

		/// <summary>
		/// Oblique (slanted) font style.
		/// </summary>
		Oblique,
	}
}
